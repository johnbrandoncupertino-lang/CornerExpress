-- CornerExpress Door Lock Installer
-- Run this as: doorlock-installer.lua
-- Requires ComputerCraft HTTP access to raw.githubusercontent.com.
local SOURCE_URL = "https://raw.githubusercontent.com/johnbrandoncupertino-lang/CornerExpress/main/doorlock%20%281%29.lua"

local function ask(prompt, default, secret)
  write(prompt)
  if default and default ~= "" then write(" [" .. default .. "]") end
  write(": ")
  local v = read(secret and "*" or nil)
  if v == "" and default then return default end
  return v
end

local function yesNo(prompt, defaultYes)
  while true do
    write(prompt .. (defaultYes and " [Y/n]: " or " [y/N]: "))
    local s = read():lower()
    if s == "" then return defaultYes end
    if s == "y" or s == "yes" then return true end
    if s == "n" or s == "no" then return false end
  end
end

local function quote(s) return string.format("%q", s) end

local function readPairingFile()
  if not disk then return nil end
  for _, side in ipairs(peripheral.getNames()) do
    if peripheral.getType(side) == "drive" and disk.isPresent(side) and disk.hasData(side) then
      local mount = disk.getMountPath(side)
      if mount then
        local path = fs.combine(mount, "doorpair.txt")
        if fs.exists(path) and not fs.isDir(path) then
          local h = fs.open(path, "r")
          if h then
            local id = h.readLine()
            local secret = h.readLine()
            h.close()
            if id and secret and id:match("^[%w_%-]+$") and #id <= 32 and #secret == 32 and secret:match("^%x+$") then
              return id, secret, path
            end
          end
        end
      end
    end
  end
  return nil
end

term.setBackgroundColor(colors.black)
term.setTextColor(colors.white)
term.clear()
term.setCursorPos(1, 1)
print("CORNEREXPRESS DOOR LOCK INSTALLER")
print("This installs the current main-branch controller as startup.lua.")
print("It does not change or erase cards.db or access.log.")
print("")

if not http then error("HTTP API unavailable. Enable HTTP in ComputerCraft config.", 0) end
write("Downloading controller... ")
local response, requestErr = http.get(SOURCE_URL, nil, true)
if not response then error("Download failed: " .. tostring(requestErr), 0) end
local source = response.readAll()
response.close()
if not source or not source:find('local ROLE = "client"', 1, true) then
  error("Downloaded file did not look like the expected controller; nothing installed.", 0)
end
print("done")

print("")
print("Install target:")
print("1) Server / admin console")
print("2) Door client")
local role
while not role do
  local c = ask("Choose 1 or 2")
  if c == "1" then role = "server"
  elseif c == "2" then role = "client"
  else print("Enter 1 or 2.") end
end

source = source:gsub('local ROLE = "[^"]+"', 'local ROLE = "' .. role .. '"', 1)

if role == "server" then
  print("")
  print("Choose a strong admin password. It is stored locally on this computer.")
  local password = ask("Admin password", nil, true)
  if #password < 8 then error("Use an admin password of at least 8 characters.", 0) end
  source = source:gsub('adminPassword%s*=%s*""', 'adminPassword = ' .. quote(password), 1)
else
  local id, secret, pairingPath = readPairingFile()
  if id and secret then
    print("")
    print("Found a valid doorpair.txt on a floppy.")
    print("Door ID: " .. id)
    if yesNo("Import this pairing file", true) then
      source = source:gsub('doorId%s*=%s*""', 'doorId = ' .. quote(id), 1)
      source = source:gsub('secret%s*=%s*""', 'secret = ' .. quote(secret), 1)
      if yesNo("Delete doorpair.txt from the floppy now", true) then
        pcall(fs.delete, pairingPath)
      end
    else
      id, secret = nil, nil
    end
  end
  if not id or not secret then
    print("")
    print("Create the door on the server first.")
    print("Use Doors > Export pairing file for easier setup, or enter credentials manually.")
    id = ask("Door ID")
    secret = ask("Door secret", nil, true)
    if not id:match("^[%w_%-]+$") or #id < 1 or #id > 32 then
      error("Invalid door ID.", 0)
    end
    if #secret ~= 32 or not secret:match("^%x+$") then
      error("Door secret must be the 32-character hexadecimal key generated by the server.", 0)
    end
    source = source:gsub('doorId%s*=%s*""', 'doorId = ' .. quote(id), 1)
    source = source:gsub('secret%s*=%s*""', 'secret = ' .. quote(secret), 1)
  end
  local side = ask("Redstone output side", "left")
  local openTime = tonumber(ask("Unlock duration in seconds", "5"))
  if not openTime or openTime < 1 or openTime > 120 or openTime ~= math.floor(openTime) then
    error("Unlock duration must be a whole number from 1 to 120.", 0)
  end
  source = source:gsub('redstoneSide%s*=%s*"left"', 'redstoneSide = ' .. quote(side), 1)
  source = source:gsub('openTime%s*=%s*5', 'openTime = ' .. tostring(openTime), 1)
end

local target = "startup.lua"
if fs.exists(target) then
  if not yesNo("startup.lua already exists. Replace it", false) then
    print("Cancelled; existing startup.lua was not changed.")
    return
  end
end

local temp = target .. ".install.tmp"
local h = fs.open(temp, "w")
if not h then error("Cannot create " .. temp, 0) end
h.write(source)
h.close()
if fs.exists(target) then fs.delete(target) end
fs.move(temp, target)

print("")
print("Installation complete: startup.lua")
print("The controller starts automatically on the next boot.")
print("Client maintenance menu: press M while the door is idle.")
print("For a safe reboot, use M > R. Errors no longer trigger reboot loops.")
print("Keep exported pairing media secure; the secret is stored on the client.")
